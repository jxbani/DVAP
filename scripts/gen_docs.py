"""Generate the challenge pages of the docs site, and the README's challenge table, from
challenges/<id>/challenge.yaml and solution.md, so they can never drift from the scoreboard.

    uv run python scripts/gen_docs.py          # rewrite the generated files
    uv run python scripts/gen_docs.py --check  # exit 1 if any is stale (CI runs this via pytest)

Challenge pages hold no spoilers (story, objective, collapsed hints); the reference solution and
the fix are on a separate page behind a warning.
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "challenges"
README = ROOT / "README.md"
TABLE_START, TABLE_END = "<!-- CHALLENGES:START -->", "<!-- CHALLENGES:END -->"
GENERATED = "<!-- Generated by scripts/gen_docs.py from challenges/{id}/: edit those, then rerun it. -->\n"

ASI = {
    "ASI01": "Agent Goal Hijack",
    "ASI02": "Tool Misuse & Exploitation",
    "ASI03": "Identity & Privilege Abuse",
    "ASI04": "Agentic Supply Chain Vulnerabilities",
    "ASI05": "Unexpected Code Execution",
    "ASI06": "Memory & Context Poisoning",
    "ASI07": "Insecure Inter-Agent Communication",
    "ASI08": "Cascading Failures",
    "ASI09": "Human-Agent Trust Exploitation",
    "ASI10": "Rogue Agents",
}
CONSEQUENCE = {  # what you see on the HMI when it works
    "C01": "Tank overflow", "C01b": "Tank overflow", "C02": "Chlorine overdose", "C03": "Tank overflow",
    "C04": "Chlorine underdose", "C05": "Direct PLC write", "C06": "Chlorine overdose", "C07": "Pump dry-run",
    "C08": "Pump dry-run", "C09": "Interlock disabled", "C10": "Unsafe setpoint keeps returning",
}


def load() -> list[dict]:
    chs = [yaml.safe_load((d / "challenge.yaml").read_text(encoding="utf-8"))
           for d in (ROOT / "challenges").iterdir() if (d / "challenge.yaml").exists()]
    return sorted(chs, key=lambda c: (c["owasp_asi"], c["id"]))


def indent(text: str) -> str:
    return "\n".join(f"    {line}" if line else "" for line in text.strip().splitlines())


def challenge_page(c: dict) -> str:
    hints = "\n\n".join(f'??? tip "Hint {i}"\n{indent(h)}' for i, h in enumerate(c["hints"], 1))
    return (
        GENERATED.format(id=c["id"])
        + f"# {c['id']} — {c['title']}\n\n"
        f"| OWASP ASI | Difficulty | What happens |\n|---|---|---|\n"
        f"| {c['owasp_asi']} {ASI[c['owasp_asi']]} | {c['difficulty']} | {CONSEQUENCE[c['id']]} |\n\n"
        f"## Story\n\n{c['story'].strip()}\n\n"
        f"## Objective\n\n{c['objective'].strip()}\n\n"
        "## Play it\n\n"
        f"Start **{c['id']}** on the scoreboard (http://127.0.0.1:8090). Starting it resets the lab to the\n"
        "challenge's starting state; the scoreboard marks it solved by itself when the attack works.\n"
        "Watch the plant on the HMI (http://127.0.0.1:8080) while you play.\n\n"
        "## Hints\n\n"
        "Open one at a time; each gives away more than the last.\n\n"
        f"{hints}\n\n"
        f"Still stuck? The [reference solution](solutions/{c['id']}.md) has the full attack and the fix\n"
        "(spoilers).\n"
    )


def solution_page(c: dict) -> str:
    body = (ROOT / "challenges" / c["id"] / "solution.md").read_text(encoding="utf-8").strip()
    body = body.split("\n", 1)[1].strip() if body.startswith("# ") else body  # our own title instead
    return (
        GENERATED.format(id=c["id"])
        + f"# {c['id']} — reference solution\n\n"
        '!!! warning "Spoilers"\n'
        f"    This page gives the whole attack away. Try the [hints](../{c['id']}.md) first.\n\n"
        f"{body}\n\n"
        f"## Mitigation\n\n{c['mitigation'].strip()}\n"
    )


def table(chs: list[dict], link) -> str:
    rows = [f"| [{c['id']}]({link(c['id'])}) | {c['title']} | {c['owasp_asi']} {ASI[c['owasp_asi']]} "
            f"| {c['difficulty']} | {CONSEQUENCE[c['id']]} |" for c in chs]
    return "| ID | Challenge | OWASP ASI | Difficulty | What happens |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n"


def index_page(chs: list[dict]) -> str:
    return (
        GENERATED.format(id="*")
        + "# Challenges\n\n"
        f"{len(chs)} challenges, mapped to the OWASP Top 10 for Agentic Applications (ASI01–ASI10). Each one\n"
        "has a story, an objective and three hints, and the scoreboard checks success automatically.\n"
        "Every page here is spoiler-free; the reference solutions are on separate pages, linked from the end\n"
        "of each challenge.\n\n"
        + table(chs, lambda cid: f"{cid}.md")
        + "\nEach challenge also has a *defended* variant: solve it, then turn [SafeEnvelope](../SAFEENVELOPE.md)\n"
        "on (`make defend`) and try again.\n"
    )


def render() -> dict[Path, str]:
    chs = load()
    files = {OUT / "index.md": index_page(chs)}
    for c in chs:
        files[OUT / f"{c['id']}.md"] = challenge_page(c)
        files[OUT / "solutions" / f"{c['id']}.md"] = solution_page(c)
    text = README.read_text(encoding="utf-8")
    pre, rest = text.split(TABLE_START, 1)
    post = rest.split(TABLE_END, 1)[1]
    site = "https://jxbani.github.io/DVAP/challenges/{}/"
    files[README] = pre + TABLE_START + "\n" + table(chs, site.format) + TABLE_END + post
    return files


def main(check: bool) -> int:
    stale = []
    for path, text in render().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print(("stale (run scripts/gen_docs.py): " if check else "wrote: ") + ", ".join(stale))
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
